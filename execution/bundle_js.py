import os

# Configuration
SOURCE_DIR = 'js/modules'
OUTPUT_FILE = 'dist/bundle.js'
ENTRY_POINT = 'js/script.js'

# Data dependencies from data/ folder
DATA_DIR = 'data'
DATA_ORDER = [
    'reference_map.js',
    'type_chart.js',
    'evo_requirements.js',
    'locations_data.js',
    'data_drops.js',
    'api_name_map.js',
    'guide_content.js'
]

# Order is critical for global scope dependencies
MODULE_ORDER = [
    'state.js',
    'utils.js',
    'data.js',
    'ui.js',
    'editor.js',
    'battle.js',
    'events.js'
]

def bundle_js():
    print(f"--- REGEN-SYSTEM: Starting JS Bundling ---")
    
    js_content = [
        "/* AUTOGENERATED BY REGEN-SYSTEM - DO NOT EDIT MANUALLY */",
        "/* BUNDLED ON: [DYNAMIC] */"
    ]

    # 1. Add Data Files
    for filename in DATA_ORDER:
        path = os.path.join(DATA_DIR, filename)
        if os.path.exists(path):
            print(f"Adding data: {filename}")
            with open(path, 'r', encoding='utf-8') as f:
                js_content.append(f"\n// --- DATA: {filename} ---\n{f.read()}")
        else:
            print(f"WARNING: Missing data file {filename}")
    
    # 2. Add modules in order
    for filename in MODULE_ORDER:
        path = os.path.join(SOURCE_DIR, filename)
        if os.path.exists(path):
            print(f"Adding module: {filename}")
            with open(path, 'r', encoding='utf-8') as f:
                js_content.append(f"\n// --- MODULE: {filename} ---\n{f.read()}")
        else:
            print(f"WARNING: Missing module {filename}")

    # 2. Add entry point
    if os.path.exists(ENTRY_POINT):
        print(f"Adding entry point: {ENTRY_POINT}")
        with open(ENTRY_POINT, 'r', encoding='utf-8') as f:
            js_content.append(f"\n// --- ENTRY POINT: {ENTRY_POINT} ---\n{f.read()}")

    # Ensure target directory exists
    os.makedirs(os.path.dirname(OUTPUT_FILE), exist_ok=True)
    
    with open(OUTPUT_FILE, 'w', encoding='utf-8') as f:
        f.write("\n".join(js_content))
        
    print(f"--- REGEN-SYSTEM: JS Bundling Complete. Output: {OUTPUT_FILE} ---")

if __name__ == "__main__":
    bundle_js()
